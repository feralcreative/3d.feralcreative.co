#!/usr/bin/env python3
"""Generate the original pumpkin's closed outer volume for rear-door infill.

Union the protected blank shell and its original lid, then retain only the
outer connected surface. This fills the cavity without replacing the sculpted
lobes with a convex hull. The authoring sources clip the result behind their
own rear joint and recut the unchanged cork socket and wire passage.
"""
import argparse
import importlib.util
from pathlib import Path
import subprocess
import tempfile

import numpy as np


def outer_surface(triangles):
    vertices, faces = np.unique(triangles.reshape(-1, 3), axis=0, return_inverse=True)
    faces = faces.reshape(-1, 3)
    parent = np.arange(len(vertices))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    for a, b, c in faces:
        a, b, c = find(a), find(b), find(c)
        parent[b] = a
        parent[c] = a
    labels = np.array([find(i) for i in range(len(vertices))])
    surfaces = []
    for label in set(labels):
        mask = labels[faces[:, 0]] == label
        part = triangles[mask]
        volume = float(np.einsum('ij,ij->i', part[:, 0], np.cross(part[:, 1], part[:, 2])).sum() / 6)
        surfaces.append((volume, mask))
    if len(surfaces) != 2 or sum(volume > 0 for volume, _ in surfaces) != 1:
        raise ValueError('Expected one outer surface and one enclosed inner surface after closing the lid')
    volume, mask = max(surfaces, key=lambda item: item[0])
    faces = faces[mask]
    used, inverse = np.unique(faces, return_inverse=True)
    return vertices[used], inverse.reshape(-1, 3), volume


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--openscad', default='/Applications/OpenSCAD.app/Contents/MacOS/OpenSCAD')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    model = root / 'library/holiday/halloween/fence-pumpkins'
    source = model / 'led-tea-light-jack-o-lantern-pumpkins-model_files'
    spec = importlib.util.spec_from_file_location('section', Path(__file__).with_name('section-outline.py'))
    section = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(section)
    with tempfile.TemporaryDirectory(prefix='pumpkin-solid-') as folder:
        folder = Path(folder)
        scad, mesh = folder / 'envelope.scad', folder / 'envelope.stl'
        scad.write_text('union(){\n'
                        f'import("{source / "blank-shell.stl"}");\n'
                        f'scale([1+0.3/23,1+0.3/23,1]) import("{source / "stem-lid.stl"}");\n'
                        '}\n')
        result = subprocess.run([args.openscad, '--export-format=binstl', '-o', str(mesh), str(scad)], capture_output=True, text=True, check=True)
        if 'ERROR' in result.stderr or 'WARNING' in result.stderr or not mesh.is_file():
            raise ValueError(result.stderr)
        vertices, faces, volume = outer_surface(section.load(mesh))
    text = '// Original pumpkin outer surface, capped by its retained lid. Generated by cad/utils/pumpkin-solid.py.\n'
    text += '// Interior-facing surface removed; used only for the closed rear-door infill volume.\n'
    text += 'module pumpkin_outer_solid() polyhedron(points=[\n'
    text += ',\n'.join('[' + ','.join(format(float(n), '.17g') for n in row) + ']' for row in vertices)
    # OpenSCAD uses clockwise polyhedron faces viewed from outside, opposite STL.
    text += '\n], faces=[\n' + ',\n'.join(str(row[::-1].tolist()) for row in faces) + '\n],convexity=10);\n'
    args.output.write_text(text)
    print(f'Outer solid: {len(vertices)} vertices, {len(faces)} triangles, {volume:.3f} mm3; {args.output}')


if __name__ == '__main__':
    main()
