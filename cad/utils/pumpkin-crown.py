#!/usr/bin/env python3
"""Sample the source pumpkin's upper surface across its back wall.

A single filled section extruded through 4.8 mm leaves daylight above the door:
the pumpkin's crown changes over that depth. Retain its actual surface as a
triangulated solid crown, rather than guessing an arc. Run from the repo root.
"""
import argparse
import importlib.util
from pathlib import Path
import numpy as np


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--back-y', type=float, default=25, help='Rear wall plane in mm')
    parser.add_argument('--wall-t', type=float, default=4.8, help='Wall depth in mm')
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location('section', Path(__file__).with_name('section-outline.py'))
    section = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(section)
    source = Path(__file__).resolve().parents[1] / 'library/holiday/halloween/fence-pumpkins/led-tea-light-jack-o-lantern-pumpkins-model_files'
    triangles = np.concatenate([section.load(source / name) for name in ('blank-shell.stl', 'stem-lid.stl')])
    # Sample only the door and its tongues. Outside this strip the existing
    # back outline remains buried in the shell. Units are millimetres.
    xs = np.linspace(-24, 24, 193)
    ys = np.linspace(args.back_y - args.wall_t, args.back_y, 25)
    floor = 19.9
    a = triangles[:, 0, :2]
    u = triangles[:, 1, :2] - a
    v = triangles[:, 2, :2] - a
    det = u[:, 0] * v[:, 1] - u[:, 1] * v[:, 0]
    keep = abs(det) > 1e-10
    triangles, a, u, v, det = [q[keep] for q in (triangles, a, u, v, det)]
    lo = triangles[:, :, :2].min(1)
    hi = triangles[:, :, :2].max(1)
    vertices = []
    for y in ys:
        row = np.where((lo[:, 1] <= y + 1e-8) & (hi[:, 1] >= y - 1e-8))[0]
        for x in xs:
            k = row[(lo[row, 0] <= x + 1e-8) & (hi[row, 0] >= x - 1e-8)]
            d = np.array([x, y]) - a[k]
            b = (d[:, 0] * v[k, 1] - d[:, 1] * v[k, 0]) / det[k]
            c = (u[k, 0] * d[:, 1] - u[k, 1] * d[:, 0]) / det[k]
            inside = (b >= -1e-8) & (c >= -1e-8) & (b + c <= 1 + 1e-8)
            z = triangles[k, 0, 2] + b * (triangles[k, 1, 2] - triangles[k, 0, 2]) + c * (triangles[k, 2, 2] - triangles[k, 0, 2])
            top = max(z[inside])
            if top <= floor:
                raise ValueError(f'Crown below its floor at {x}, {y}')
            vertices.append((x, y, top))
    nx, ny = len(xs), len(ys)
    faces = []
    # OpenSCAD polyhedron faces are clockwise viewed from outside.
    for j in range(ny - 1):
        for i in range(nx - 1):
            q = j * nx + i
            faces += [(q, q + nx + 1, q + 1), (q, q + nx, q + nx + 1)]
    boundary = (list(range(nx)) + [j * nx + nx - 1 for j in range(1, ny)] +
                list(range(ny * nx - 2, (ny - 1) * nx - 1, -1)) +
                [j * nx for j in range(ny - 2, 0, -1)])
    bottom = len(vertices)
    vertices += [(vertices[q][0], vertices[q][1], floor) for q in boundary]
    for i, q in enumerate(boundary):
        j = (i + 1) % len(boundary)
        faces.append((q, boundary[j], bottom + j, bottom + i))
    faces.append(tuple(range(bottom, len(vertices))))
    with args.output.open('w') as f:
        f.write('// Generated by utils/pumpkin-crown.py; source blank shell and original lid.\n')
        f.write(f'// X +/-24, Y {args.back_y - args.wall_t:g}..{args.back_y:g} mm; samples 0.25 x {args.wall_t / 24:g} mm; floor Z=19.9.\n')
        f.write('module back_crown() polyhedron(points=[\n')
        f.write(',\n'.join('[' + ','.join(f'{v:.6f}' for v in p) + ']' for p in vertices))
        f.write('\n], faces=[\n' + ',\n'.join(str(list(p)) for p in faces) + '\n], convexity=10);\n')
    print(f'{len(vertices)} vertices; {len(faces)} faces; {args.output}')


if __name__ == '__main__':
    main()
